"""
Конфигурация проекта.

Секреты (токен бота, ключ Gemini) НЕ хранятся в коде — они читаются
из переменных окружения / файла .env. Локально создайте файл .env рядом
с этим файлом (по образцу .env.example). На хостинге (Render и т.п.)
эти же переменные задаются в панели управления — .env там не нужен.
"""

import os
from pathlib import Path

from dotenv import load_dotenv

BASE_DIR = Path(__file__).resolve().parent
load_dotenv(BASE_DIR / ".env")

# ---------------------------------------------------------------------------
# Где хранятся ИЗМЕНЯЕМЫЕ данные (токены пользователей, состояние синхрони-
# зации, скачанные учебники и т.п.)
# ---------------------------------------------------------------------------
# Локально — просто рядом с проектом. На хостинге с постоянным диском
# (например, Render Persistent Disk) задайте переменную DATA_ROOT равной
# пути монтирования диска (например, /var/data) — тогда все эти файлы
# переживут редеплой и перезапуск, а не потеряются вместе с контейнером.
DATA_ROOT: Path = Path(os.getenv("DATA_ROOT", str(BASE_DIR)))
DATA_ROOT.mkdir(parents=True, exist_ok=True)

# ---------------------------------------------------------------------------
# Секреты
# ---------------------------------------------------------------------------
TELEGRAM_BOT_TOKEN: str = os.getenv("TELEGRAM_BOT_TOKEN", "")

# Можно указать несколько ключей Gemini через запятую (GEMINI_API_KEY=
# key1,key2,key3) — например, если у вас несколько бесплатных ключей от
# разных Google-аккаунтов. Бот будет пробовать их по очереди в случайном
# порядке: если у одного кончилась квота/он вернул ошибку — пробует
# следующий, а не сдаётся сразу. Один ключ (без запятых) тоже работает
# как раньше.
GEMINI_API_KEY: str = os.getenv("GEMINI_API_KEY", "")
GEMINI_API_KEYS: list[str] = [
    key.strip() for key in GEMINI_API_KEY.split(",") if key.strip()
]

if not TELEGRAM_BOT_TOKEN:
    raise RuntimeError(
        "TELEGRAM_BOT_TOKEN не задан. Создайте файл .env "
        "(см. .env.example) и укажите там токен бота."
    )
if not GEMINI_API_KEYS:
    raise RuntimeError(
        "GEMINI_API_KEY не задан. Создайте файл .env "
        "(см. .env.example) и укажите там ключ Gemini API "
        "(можно несколько через запятую)."
    )

# ---------------------------------------------------------------------------
# Google OAuth / Classroom
# ---------------------------------------------------------------------------
# GOOGLE_CREDENTIALS_PATH может быть как относительным именем файла рядом
# с проектом (локально), так и абсолютным путём — например, путём к
# Render Secret File (/etc/secrets/credentials.json). Абсолютный путь
# всегда побеждает relative join ниже.
GOOGLE_CREDENTIALS_FILE: Path = BASE_DIR / os.getenv(
    "GOOGLE_CREDENTIALS_PATH", "credentials.json"
)

# ---------------------------------------------------------------------------
# OAuth callback — веб-сервер, который автоматически ловит редирект от Google
# ---------------------------------------------------------------------------
# Раньше redirect_uri был жёстко "http://localhost" — там никто не слушал,
# и браузер зависал в бесконечной загрузке, а код приходилось копировать
# руками. Теперь на этом порту реально поднят веб-сервер
# (services/oauth_server.py), который сам принимает код и сохраняет токен.
#
# Локально — ничего менять не нужно, всё работает "из коробки" (браузер
# и бот на одной машине) или через туннель (ngrok и т.п.).
#
# На Render (Web Service) порт задаёт сама платформа через переменную
# PORT — мы её подхватываем автоматически. Останется только задать
# OAUTH_REDIRECT_BASE_URL = публичный адрес сервиса и прописать тот же
# адрес + "/oauth/callback" как Authorized redirect URI в Google Cloud
# Console (тип OAuth-клиента — "Web application", не "Desktop app").
OAUTH_CALLBACK_HOST: str = os.getenv("OAUTH_CALLBACK_HOST", "0.0.0.0")
OAUTH_CALLBACK_PORT: int = int(
    os.getenv("PORT", os.getenv("OAUTH_CALLBACK_PORT", "8765"))
)
OAUTH_REDIRECT_BASE_URL: str = os.getenv(
    "OAUTH_REDIRECT_BASE_URL", f"http://localhost:{OAUTH_CALLBACK_PORT}"
)
OAUTH_REDIRECT_URI: str = f"{OAUTH_REDIRECT_BASE_URL}/oauth/callback"

GOOGLE_SCOPES: list[str] = [
    "https://www.googleapis.com/auth/classroom.courses.readonly",
    "https://www.googleapis.com/auth/classroom.coursework.me.readonly",
    "https://www.googleapis.com/auth/drive.readonly",
]

TOKENS_DIR: Path = DATA_ROOT / "tokens"
TOKENS_DIR.mkdir(exist_ok=True)

# ---------------------------------------------------------------------------
# Приём апдейтов Telegram: webhook вместо long polling
# ---------------------------------------------------------------------------
# Polling держит с Telegram постоянное открытое соединение и крутится
# 24/7 — на бесплатных хостингах это либо не даёт процессу "уснуть", либо
# просто жжёт часы тарифа впустую. Webhook вместо этого — обычный HTTP-
# эндпоинт: Telegram сам стучится к нам, когда есть новое сообщение,
# а всё остальное время сервис может простаивать/спать.
#
# USE_WEBHOOK=true  — включить режим webhook (продакшн, например Render).
# USE_WEBHOOK=false — обычный polling (по умолчанию, удобно для локальной
#                     разработки: не нужен публичный адрес).
USE_WEBHOOK: bool = os.getenv("USE_WEBHOOK", "false").strip().lower() in (
    "1", "true", "yes", "on",
)

# Секретный сегмент пути вебхука — чтобы никто посторонний не мог слать
# на этот адрес поддельные апдейты, зная только домен сервиса. Если явно
# не задан, используется сам токен бота (он и так секретный).
WEBHOOK_SECRET: str = os.getenv("WEBHOOK_SECRET", TELEGRAM_BOT_TOKEN)
WEBHOOK_PATH: str = f"/webhook/{WEBHOOK_SECRET}"
WEBHOOK_URL: str = f"{OAUTH_REDIRECT_BASE_URL}{WEBHOOK_PATH}"

# ---------------------------------------------------------------------------
# Фоновая синхронизация курсов
# ---------------------------------------------------------------------------
# Папка, где хранится "последнее известное" множество курсов каждого
# пользователя — чтобы понимать, какие курсы новые.
SYNC_STATE_DIR: Path = DATA_ROOT / "data" / "sync_state"
SYNC_STATE_DIR.mkdir(parents=True, exist_ok=True)

# Как часто (в секундах) опрашивать Classroom API в фоне на предмет новых
# курсов. Используется только в режиме polling (USE_WEBHOOK=false), где
# синхронизация всё ещё крутится встроенным циклом внутри процесса.
# Можно переопределить через .env (SYNC_INTERVAL_SECONDS=30 и т.д.).
SYNC_INTERVAL_SECONDS: int = int(os.getenv("SYNC_INTERVAL_SECONDS", "60"))

# ---------------------------------------------------------------------------
# Заглушка для внешнего крона (эндпоинт GET /cron/sync)
# ---------------------------------------------------------------------------
# В режиме webhook (USE_WEBHOOK=true) встроенный бесконечный цикл
# синхронизации не запускается — иначе он сам не давал бы бесплатному
# сервису "засыпать" между запросами, и весь смысл вебхука терялся бы.
# Вместо этого проверку Classroom по всем пользователям запускает один
# HTTP-запрос на /cron/sync — его нужно дёргать снаружи по расписанию,
# например бесплатным cron-job.org / UptimeRobot / GitHub Actions cron
# раз в SYNC_INTERVAL_SECONDS. CRON_SECRET — простая защита эндпоинта от
# посторонних вызовов (передаётся как ?key=... или заголовком X-Cron-Key).
# Если оставить пустым — эндпоинт открыт для всех (годится, если адрес
# сервиса никому не известен, но лучше задать секрет).
CRON_SECRET: str = os.getenv("CRON_SECRET", "")

# ---------------------------------------------------------------------------
# Админы
# ---------------------------------------------------------------------------
# Telegram user_id (числовые ID, не @username) через запятую — этим
# пользователям в главном меню показывается дополнительная кнопка
# "Загрузить учебник". Узнать свой user_id можно у @userinfobot в Telegram.
ADMIN_IDS: set[int] = {
    int(uid.strip()) for uid in os.getenv("ADMIN_IDS", "").split(",") if uid.strip().isdigit()
}

# ---------------------------------------------------------------------------
# Gemini
# ---------------------------------------------------------------------------
GEMINI_MODEL_NAME: str = os.getenv("GEMINI_MODEL_NAME", "gemini-flash-latest")

# Резервные модели — если основная модель перегружена (503) на ВСЕХ ключах
# подряд, бот пробует эти модели по очереди, прежде чем сдаться. Обычно
# перегружен бывает какой-то один конкретный "горячий" алиас модели, а не
# вся линейка сразу — соседняя модель в этот момент часто отвечает нормально.
# Задать свой список можно через .env: GEMINI_FALLBACK_MODELS=model1,model2
GEMINI_FALLBACK_MODELS: list[str] = [
    m.strip()
    for m in os.getenv(
        "GEMINI_FALLBACK_MODELS", "gemini-2.5-flash,gemini-2.0-flash"
    ).split(",")
    if m.strip() and m.strip() != GEMINI_MODEL_NAME
]

# Системний промпт для Gemini. Важливі вимоги нижче з'явилися не просто
# так, а через конкретні скарги на те, як виглядала відповідь:
# - без привітань і "води" на кшталт "Привіт! З радістю допоможу..." —
#   відповідь одразу йде "по суті", як у зошиті;
# - без markdown-розмітки (##, **, $$...$$ тощо) — відповідь потім
#   малюється як зображення "аркуша в клітинку" (services/notebook_render),
#   і символи розмітки там виглядали б як сміття прямо в тексті;
# - фіксована структура (Дано / Розв'язання / Відповідь), щоб
#   notebook_render і короткий витяг відповіді (gemini_service.
#   _extract_short_answer) могли на неї покладатися.
